#include "../../ps4/src/ui_png_transport.h"
#include <assert.h>
#include <stdio.h>
#include <string.h>
static const unsigned char png[]={
0x89,0x50,0x4e,0x47,0x0d,0x0a,0x1a,0x0a,0x00,0x00,0x00,0x0d,0x49,0x48,0x44,0x52,0x00,0x00,0x00,0x02,0x00,0x00,0x00,0x02,0x08,0x06,0x00,0x00,0x00,0x72,0xb6,0x0d,0x24,0x00,0x00,0x00,0x14,0x49,0x44,0x41,0x54,0x78,0x9c,0x63,0x94,0xf4,0xde,0xf2,0x9f,0x81,0x81,0x81,0x81,0x89,0x01,0x0a,0x00,0x1f,0x0d,0x02,0x1b,0x4c,0x07,0x75,0x81,0x00,0x00,0x00,0x00,0x49,0x45,0x4e,0x44,0xae,0x42,0x60,0x82};
int main(void) {
    assert(ui_png_crc_valid(png,sizeof png));
    unsigned char buffer[512]={};size_t len=sizeof png;
    memcpy(buffer,png,len);
    assert(ui_png_ftp_validate(buffer,&len)==0 && len==sizeof png);
    /* Simulate naive LF -> CRLF from FTP ASCII transport. */
    size_t n=0;
    for(size_t i=0;i<sizeof png;++i) {
        if(png[i]=='\n')buffer[n++]='\r';
        buffer[n++]=png[i];
    }
    assert(n>sizeof png);
    assert(!ui_png_crc_valid(buffer,n));
    assert(ui_png_ftp_validate(buffer,&n)==1);
    assert(n==sizeof png && memcmp(buffer,png,n)==0);
    memcpy(buffer,png,sizeof png);
    buffer[50]^=1;
    n=sizeof png;
    assert(ui_png_ftp_validate(buffer,&n)<0);
    assert(!ui_png_crc_valid(NULL,0));
    n=sizeof png;
    assert(ui_png_ftp_validate(NULL,&n)<0);
    n=2u*1024u*1024u+1u;
    assert(ui_png_ftp_validate(buffer,&n)<0);
    puts("UI_PNG_TRANSPORT_HOST_OK");
    return 0;
}
