#include "../../ps4/src/ui_image.h"
#include <assert.h>
#include <stdio.h>
#include <string.h>
static const unsigned char png_rgba[] = {
0x89,0x50,0x4e,0x47,0x0d,0x0a,0x1a,0x0a,0x00,0x00,0x00,0x0d,0x49,0x48,0x44,0x52,0x00,0x00,0x00,0x02,0x00,0x00,0x00,0x02,0x08,0x06,0x00,0x00,0x00,0x72,0xb6,0x0d,0x24,0x00,0x00,0x00,0x14,0x49,0x44,0x41,0x54,0x78,0x9c,0x63,0x94,0xf4,0xde,0xf2,0x9f,0x81,0x81,0x81,0x81,0x89,0x01,0x0a,0x00,0x1f,0x0d,0x02,0x1b,0x4c,0x07,0x75,0x81,0x00,0x00,0x00,0x00,0x49,0x45,0x4e,0x44,0xae,0x42,0x60,0x82
};
static uint32_t pixels[UI_ICON_PIXELS];
int main(void) {
    memset(pixels,0,sizeof pixels);
    assert(ui_image_thumbnail(png_rgba,sizeof(png_rgba),
                              pixels,UI_ICON_PIXELS)==0);
    for(size_t i=0;i<UI_ICON_PIXELS;i++)
        assert(pixels[i] == 0xFF194BB4u);
    assert(ui_image_thumbnail(png_rgba,sizeof(png_rgba),pixels,
                              UI_ICON_PIXELS-1)==-1);
    assert(ui_image_thumbnail(NULL,sizeof(png_rgba),pixels,
                              UI_ICON_PIXELS)==-1);
    unsigned char invalid[sizeof png_rgba];
    memcpy(invalid,png_rgba,sizeof invalid);
    invalid[0]='X';
    assert(ui_image_thumbnail(invalid,sizeof invalid,pixels,
                              UI_ICON_PIXELS)==-2);
    memcpy(invalid,png_rgba,sizeof invalid);
    invalid[16]=0x00;invalid[17]=0x00;invalid[18]=0x04;invalid[19]=0x01;
    assert(ui_image_thumbnail(invalid,sizeof invalid,pixels,
                              UI_ICON_PIXELS)<0);
    puts("UI_IMAGE_HOST_OK");
    return 0;
}
